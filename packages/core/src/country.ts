const ASSIGNED = new Set(ISO_3166_1_ALPHA2_CODES);

/**
 * Whether a value is an officially assigned ISO 3166-1 alpha-2 code, in upper case: "IT" and "DE"
 * are; "it", "ITA", "ZZ", "EU", "UN" and "XA" are not.
 */
export function isAssignedCountryCode(value: unknown): value is string {
  return typeof value === "string" && ASSIGNED.has(value);
}
